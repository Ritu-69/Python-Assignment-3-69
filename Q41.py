numbers = [10, 20, 30, 40, 50, 60, 70]

print("Original list:", numbers)
print("Elements from index 1 to 4:", numbers[1:5])    # [20, 30, 40, 50]
print("First three elements:", numbers[:3])           # [10, 20, 30]
print("From index 3 to the end:", numbers[3:])        # [40, 50, 60, 70]
print("Every second element:", numbers[::2])          # [10, 30, 50, 70]
print("Reversed list:", numbers[::-1])                # [70, 60, 50, 40, 30, 20, 10]
