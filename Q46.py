my_tuple = ('Python', 'Java', 'C++', 'JavaScript')

# Positive indexing (starts at 0 from the left)
print("First element (index 0):", my_tuple[0])
print("Third element (index 2):", my_tuple[2])

# Negative indexing (starts at -1 from the right)
print("Last element (index -1):", my_tuple[-1])
print("Second to last element (index -2):", my_tuple[-2])
